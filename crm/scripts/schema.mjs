#!/usr/bin/env node
// core/schema.sql is the database as the migrations leave it: they are applied in order to an empty SQLite database.
//   node scripts/schema.mjs           rewrite core/schema.sql
//   node scripts/schema.mjs --check   fail when core/schema.sql is behind the migrations (CI)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

const crm = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(crm, '..', 'core', 'schema.sql');
const db = new DatabaseSync(':memory:');
const files = readdirSync(join(crm, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
for (const f of files) db.exec(readFileSync(join(crm, 'migrations', f), 'utf8'));
const rows = db.prepare("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, tbl_name, type, name").all();
const head = `-- Hunt database schema (Cloudflare D1 / SQLite), generated by crm/scripts/schema.mjs from crm/migrations (${files.length} files).
-- Do not edit: add a migration, then run \`node scripts/schema.mjs\` in crm/. Timestamps are ISO-8601 UTC strings; JSON columns hold TEXT.
`;
const txt = head + rows.map((r) => `\n${r.sql.trim()};`).join('\n') + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== txt) { console.log('core/schema.sql is behind the migrations: run node scripts/schema.mjs in crm/'); process.exit(1); }
  console.log(`schema: core/schema.sql matches ${files.length} migrations`);
} else {
  writeFileSync(out, txt);
  console.log(`schema: ${rows.filter((r) => r.type === 'table').length} tables, ${rows.length} objects → core/schema.sql`);
}
