#!/usr/bin/env node
// web/types/rows.ts: one interface per database table, generated from crm/migrations (applied to an empty SQLite database),
// so the Mini App's types follow the real columns. JSON columns are TEXT here; the API types (web/types/api.ts) refine them.
//   node scripts/web-rows.mjs           rewrite web/types/rows.ts
//   node scripts/web-rows.mjs --check   fail when it is behind the migrations (CI)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

const crm = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(crm, 'web', 'types', 'rows.ts');
const db = new DatabaseSync(':memory:');
for (const f of readdirSync(join(crm, 'migrations')).filter((x) => x.endsWith('.sql')).sort()) db.exec(readFileSync(join(crm, 'migrations', f), 'utf8'));
const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map((r) => r.name);
const tsType = (t) => (/INT/i.test(t) ? 'number' : /REAL|FLOA|DOUB|NUM/i.test(t) ? 'number' : /BLOB/i.test(t) ? 'Uint8Array' : 'string');
const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
let txt = '// Generated by crm/scripts/web-rows.mjs from crm/migrations. Do not edit: add a migration, then run `node scripts/web-rows.mjs` in crm/.\n';
for (const t of tables) {
  const cols = db.prepare(`SELECT name, type, "notnull" nn, pk FROM pragma_table_info(?)`).all(t);
  txt += `\nexport interface ${pascal(t)}Row {\n${cols.map((c) => `  ${/^[a-z_][a-z0-9_]*$/i.test(c.name) ? c.name : JSON.stringify(c.name)}: ${tsType(c.type)}${c.nn || c.pk ? '' : ' | null'};`).join('\n')}\n}\n`;
}
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== txt) { console.log('web/types/rows.ts is behind the migrations: run node scripts/web-rows.mjs in crm/'); process.exit(1); }
  console.log(`web-rows: ${tables.length} tables match`);
} else {
  writeFileSync(out, txt);
  console.log(`web-rows: ${tables.length} tables → web/types/rows.ts`);
}
