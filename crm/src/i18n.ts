export type Key = keyof (typeof T)['en'];

export function t(lang: string | null | undefined, k: Key, vars: Record<string, string | number> = {}): string {
  const l: Lang = lang === 'ru' ? 'ru' : 'en';
  return (T[l][k] as string).replace(/\{(\w+)\}/g, (_, x) => String(vars[x] ?? ''));
}

export function pickLang(code: string | undefined | null): Lang {
  return code && /^(ru|uk|be|kk)/.test(code) ? 'ru' : 'en';
}

