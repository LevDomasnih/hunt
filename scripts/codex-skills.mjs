#!/usr/bin/env node
// Codex has no slash commands, only skills: makes plugins/hunt/codex-skills/<command>/SKILL.md from plugins/hunt/commands/<command>.md.
// Only the Codex manifest (.codex-plugin/plugin.json) points at codex-skills/, so Claude Code keeps its commands and sees no copies.
//   node scripts/codex-skills.mjs           write
//   node scripts/codex-skills.mjs --check   exit 1 if a skill is missing or stale
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const plugin = join(dirname(fileURLToPath(import.meta.url)), '..', 'plugins', 'hunt');
const commands = join(plugin, 'commands');
const out = join(plugin, 'codex-skills');
const check = process.argv.includes('--check');

function parse(name, text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`commands/${name}.md: no frontmatter`);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([a-z-]+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].replace(/^"(.*)"$/, '$1');
  }
  if (!meta.description) throw new Error(`commands/${name}.md: no description`);
  return { meta, body: m[2].trim() };
}

function skill(name, { meta, body }) {
  const hint = meta['argument-hint'] ? ` (${meta['argument-hint']})` : '';
  const description = `${meta.description}. Codex form of the Claude Code command /hunt:${name}: use when the user invokes it or asks for exactly this.`;
  return `---
name: ${name}
description: ${JSON.stringify(description)}
---
<!-- Generated by scripts/codex-skills.mjs from commands/${name}.md. Edit the command, then run the script. -->

# /hunt:${name}

ARGUMENTS = what the user wrote with this request${hint}; empty if nothing. Skills named below are this plugin's skills (\`hunt:<name>\` in Codex), tools are the tools of its MCP servers (hunt, hunt-telegram, hunt-browser, hunt-bridge).

${body.replaceAll('$ARGUMENTS', 'ARGUMENTS')}
`;
}

const want = new Map();
for (const f of readdirSync(commands).filter((f) => f.endsWith('.md')).sort()) {
  const name = f.slice(0, -3);
  want.set(name, skill(name, parse(name, readFileSync(join(commands, f), 'utf8'))));
}

const stale = [];
for (const [name, text] of want) {
  const p = join(out, name, 'SKILL.md');
  if (!existsSync(p) || readFileSync(p, 'utf8') !== text) stale.push(name);
}
const extra = existsSync(out) ? readdirSync(out).filter((d) => !want.has(d)) : [];

if (check) {
  if (stale.length || extra.length) {
    console.error(`codex-skills out of date: ${[...stale, ...extra.map((d) => `${d} (no command)`)].join(', ')}. Run: node scripts/codex-skills.mjs`);
    process.exit(1);
  }
  console.log(`codex-skills: ${want.size} up to date`);
} else {
  for (const name of stale) { mkdirSync(join(out, name), { recursive: true }); writeFileSync(join(out, name, 'SKILL.md'), want.get(name)); }
  for (const d of extra) rmSync(join(out, d), { recursive: true, force: true });
  console.log(`codex-skills: ${stale.length} written, ${extra.length} removed, ${want.size} total`);
}
